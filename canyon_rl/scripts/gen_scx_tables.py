#!/usr/bin/env python3
"""Extract the SCX wave tables from the original GBDK source.

The canyon shape is driven by lookup_tables.c: a flat "merged segment table"
that is scrolled backwards two bytes per frame, plus per-difficulty slices into
it (scx_tables[]).  We re-emit exactly those bytes as C++ data so the port
follows the original canyon geometry.

Usage: gen_scx_tables.py <path to canyon-racer/src/lookup_tables.c> <out.cpp>
"""

import re
import sys

# Addresses are multiples of 144 entries (SCX_TABLE_SEG_SIZE).
# (start, stop) pairs copied from scx_tables[] in the original source.
SCX_TABLE_RANGES = [
    (11, 8),
    (8, 6),
    (8, 6),
    (3, 0),
    (6, 3),
    (6, 3),
    (3, 0),
    (3, 0),
    (3, 0),
    (6, 3),
    (13, 11),
    (13, 11),
    (11, 10),
    (9, 8),   # SCX_TABLE_STR_LOW
    (10, 9),  # SCX_TABLE_STR_STR
]


def extract(path):
    src = open(path).read()
    defs = {}
    for m in re.finditer(r"^#define\s+(SCX_TABLE_\w+)\s+(.*)$", src, re.M):
        name, body = m.group(1), m.group(2).strip()
        vals, ok = [], True
        for tok in body.split(","):
            tok = tok.strip().replace("(uint8_t)", "")
            if not tok:
                continue
            if not re.fullmatch(r"-?\d+", tok):
                ok = False
                break
            vals.append(int(tok) & 0xFF)
        if ok and vals:
            defs[name] = vals

    body = re.search(
        r"scx_merged_segment_table\[\]\s*=\s*\{(.*?)\n\};", src, re.S
    ).group(1)
    body = re.sub(r"//[^\n]*", "", body)
    segs = []
    for tok in re.findall(r"SCX_TABLE_\w+", body):
        segs.extend(defs[tok])
    assert len(segs) == 14 * 144, f"unexpected merged table size {len(segs)}"
    return segs


def emit(segs, out):
    lines = [
        "// Generated by scripts/gen_scx_tables.py from canyon-racer/src/lookup_tables.c",
        "// Original canyon wave data (c) 2023 bbbbbr, CC-BY-NC-SA 4.0.",
        '#include "canyon/game.hpp"',
        "",
        "namespace canyon {",
        "",
        "const uint8_t kScxMergedTable[2016] = {",
    ]
    for i in range(0, len(segs), 16):
        lines.append("    " + ",".join(str(v) for v in segs[i : i + 16]) + ",")
    lines += ["};", "", "const ScxTableEntry kScxTables[15] = {"]
    for s, e in SCX_TABLE_RANGES:
        lines.append("    {%d, %d}," % (s * 144, e * 144))
    lines += ["};", "", "}  // namespace canyon", ""]
    open(out, "w").write("\n".join(lines))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    emit(extract(sys.argv[1]), sys.argv[2])